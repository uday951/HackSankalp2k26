class GeocodingService {
  private cache = new Map<string, PlaceResult[]>()
  private abortController: AbortController | null = null

  /**
   * Search for real-world places by text query.
   * Performs an instant fuzzy match against curated landmarks, then queries the Photon OSM geocoding API.
   */
  async searchPlaces(query: string, limit = 6): Promise<PlaceResult[]> {
    const trimmed = query.trim()
    if (!trimmed || trimmed.length < 2) return []

    const cacheKey = trimmed.toLowerCase()
    if (this.cache.has(cacheKey)) {
      return this.cache.get(cacheKey)!
    }

    // Cancel any in-flight request
    if (this.abortController) {
      this.abortController.abort()
    }
    this.abortController = new AbortController()

    // 1. Match against curated landmarks first
    const terms = cacheKey.split(/\s+/)
    const localMatches = CURATED_LANDMARKS.filter((item) => {
      const target = `${item.name} ${item.address}`.toLowerCase()
      return terms.every((t) => target.includes(t))
    })

    // 2. Fetch from Photon OpenStreetMap search endpoint (or backend proxy)
    let apiMatches: PlaceResult[] = []
    try {
      // Photon is specifically designed for OpenStreetMap search-as-you-type
      const url = `https://photon.komoot.io/api/?q=${encodeURIComponent(trimmed)}&lat=17.385&lon=78.486&limit=${limit}`
      const response = await fetch(url, {
        signal: this.abortController.signal,
        headers: { Accept: 'application/json' },
      })

      if (response.ok) {
        const json = await response.json()
        if (json.features && Array.isArray(json.features)) {
          apiMatches = json.features.map((feat: any, idx: number) => {
            const props = feat.properties || {}
            const [lng, lat] = feat.geometry.coordinates

            const name = props.name || props.street || props.city || trimmed
            const parts = [props.street, props.city, props.state, props.country].filter(Boolean)
            const address = parts.length > 0 ? parts.join(', ') : `${name}, Telangana`

            return {
              id: `osm-${props.osm_id || idx}-${Date.now()}`,
              name,
              address,
              lat,
              lng,
              type: props.osm_value || props.type || 'place',
              district: props.district,
              city: props.city,
              state: props.state,
            }
          })
        }
      }
    } catch (e: any) {
      if (e.name !== 'AbortError') {
        console.warn('[GeocodingService] External search error, using local landmarks:', e.message)
      }
    }

    // Merge results, giving priority to local exact matches, deduplicating by proximity
    const combined: PlaceResult[] = [...localMatches]
    for (const item of apiMatches) {
      const alreadyExists = combined.some(
        (c) => Math.hypot(c.lat - item.lat, c.lng - item.lng) < 0.005 || c.name.toLowerCase() === item.name.toLowerCase()
      )
      if (!alreadyExists) {
        combined.push(item)
      }
    }

    const results = combined.slice(0, limit)
    this.cache.set(cacheKey, results)
    return results
  }

  /**
   * Reverse geocode a latitude and longitude into a human-readable place result
   */
  async reverseGeocode(lat: number, lng: number): Promise<PlaceResult> {
    // Check if close to known landmarks
    let nearest: PlaceResult | null = null
    let minDist = Infinity

    for (const item of CURATED_LANDMARKS) {
      const dist = Math.hypot(item.lat - lat, item.lng - lng)
      if (dist < minDist) {
        minDist = dist
        nearest = item
      }
    }

    if (nearest && minDist < 0.008) {
      return nearest
    }

    // Attempt Photon reverse geocode
    try {
      const url = `https://photon.komoot.io/reverse?lat=${lat}&lon=${lng}`
      const response = await fetch(url, { headers: { Accept: 'application/json' } })
      if (response.ok) {
        const json = await response.json()
        const feat = json.features?.[0]
        if (feat) {
          const props = feat.properties || {}
          const name = props.name || props.street || 'Selected Location'
          const parts = [props.street, props.city, props.state].filter(Boolean)
          const address = parts.length > 0 ? parts.join(', ') : `${lat.toFixed(4)}, ${lng.toFixed(4)}`
          return {
            id: `rev-${lat}-${lng}`,
            name,
            address,
            lat,
            lng,
            type: 'pin',
          }
        }
      }
    } catch (e) {
      // Fallback
    }

    return {
      id: `coord-${lat.toFixed(4)}-${lng.toFixed(4)}`,
      name: `Location (${lat.toFixed(4)}, ${lng.toFixed(4)})`,
      address: `Selected GPS Coordinates, Hyderabad`,
      lat,
      lng,
      type: 'pin',
    }
  }
}

export const geocodingService = new GeocodingService()
